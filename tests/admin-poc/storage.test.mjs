test('PG-12: in-flight SQL commit linearizes before revocation; later writes deny', async (t) => {
  const f = await initialized(t);
  await changeRole(f.client, f.schema, f.installationId, f.actors[0], f.actors[1], 'admin', 0);
  const edit = worker(t, f, { action: 'catalog', actor: f.actors[1], requestId: randomUUID(), expectedRevision: 0, snapshot: snapshot(), pauseAfterAuthorization: true });
  await start(edit); await edit.waitFor('afterAuthorization');
  const revoke = worker(t, f, { action: 'role', actor: f.actors[0], target: f.actors[1], role: 'user', expectedRevision: 1 });
  await start(revoke);
  const revokePid = (await revoke.waitFor('connected')).backendPid;
  let observedLock = false;
  for (let i = 0; i < 100; i++) {
    const result = await f.client.query("SELECT wait_event_type FROM pg_stat_activity WHERE pid=$1", [revokePid]);
    if (result.rows[0]?.wait_event_type === 'Lock') { observedLock = true; break; }
    await new Promise((resolve) => setTimeout(resolve, 10));
  }
  assert.ok(observedLock, 'revocation actually waits on the database, not a JavaScript mock');
  edit.resume('afterAuthorization');
  assert.equal((await edit.waitFor('result')).ok, true);
  assert.equal((await revoke.waitFor('result')).ok, true);
  await assert.rejects(() => commitCatalog(f.client, f.schema, f.installationId, f.actors[1], randomUUID(), 1, snapshot('later')), /POC_FORBIDDEN/);
});

