test('PG-14 COUNTEREXAMPLE: SQL lock plus filesystem rename alone is unsafe after disconnection', async (t) => {
  const f = await initialized(t);
  await changeRole(f.client, f.schema, f.installationId, f.actors[0], f.actors[1], 'admin', 0);
  const directory = await mkdtemp(path.join(os.tmpdir(), 'oaktech-poc-counterexample-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await writeFile(path.join(directory, 'catalog.json'), JSON.stringify(snapshot('before')));
  const w = worker(t, f, { action: 'unsafe-json-demonstration', actor: f.actors[1], snapshot: snapshot('unauthorized-late-write') }, { OAKTECH_POC_UNSAFE_OUTPUT: directory });
  await start(w); await w.waitFor('afterAuthorization');
  await terminateBackend(f, (await w.waitFor('connected')).backendPid);
  await changeRole(f.client, f.schema, f.installationId, f.actors[0], f.actors[1], 'user', 1);
  w.resume('afterAuthorization'); await w.waitFor('unsafeFileWritten');
  assert.equal((await w.waitFor('result')).ok, false, 'SQL reports failure');
  assert.equal(JSON.parse(await readFile(path.join(directory, 'catalog.json'), 'utf8')).products[0].slug, 'unauthorized-late-write', 'filesystem changed after acknowledged revocation despite SQL rollback');
});

