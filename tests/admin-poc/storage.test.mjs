const url = process.env.OAKTECH_POC_DATABASE_URL;
const snapshot = (value = 'fixture') => ({ schemaVersion: 1, products: [{ slug: value }], releases: [] });

async function fixture(t, count = 4) {
  const client = await connectTestDatabase(url);
  const schema = `oaktech_poc_${randomUUID().replaceAll('-', '')}`;
  const installationId = randomUUID();
  const token = randomBytes(32).toString('hex');
  const children = [];
  const actors = Array.from({ length: count }, () => randomUUID());
  await prepareTestSchema(client, schema, installationId, token, actors);
  await client.query(`SET search_path TO "${schema}", pg_catalog`);
  t.after(async () => {
    for (const child of children) {
      if (child.exitCode === null && child.signalCode === null) { const done = new Promise((resolve) => child.once('exit', resolve)); child.kill('SIGKILL'); await done; }
    }
    // Schema name was generated by this test, never copied from connection input.
    await client.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await client.end();
  });
  return { client, schema, installationId, token, actors, children };
}

function worker(t, fixture, operation, extraEnv = {}) {
  const child = fork(new URL('../../scripts/admin-poc/worker.mjs', import.meta.url), [], {
    env: { ...process.env, OAKTECH_POC_DATABASE_URL: url, ...extraEnv },
    stdio: ['ignore', 'ignore', 'pipe', 'ipc'],
  });
  fixture.children.push(child);
  const events = [];
  const pending = [];
  let exited = false;
  const resolveEvent = (value) => {
    events.push(value);
    for (const listener of [...pending]) {
      if (listener.kind === value.kind) { clearTimeout(listener.timer); pending.splice(pending.indexOf(listener), 1); listener.resolve(value); }
    }
  };
  child.on('message', resolveEvent);
  child.on('exit', () => {
    exited = true;
    for (const listener of pending.splice(0)) { clearTimeout(listener.timer); listener.reject(new Error(`POC_WORKER_EXIT_BEFORE_${listener.kind}`)); }
  });
  child.on('error', () => resolveEvent({ kind: 'result', ok: false, code: 'POC_WORKER_START_FAILED' }));
  child.stderr.resume();
  t.after(async () => {
    if (!exited) { const done = new Promise((resolve) => child.once('exit', resolve)); child.kill('SIGKILL'); await done; }
  });
  child.send({ schema: fixture.schema, installationId: fixture.installationId, ...operation });
  const waitFor = (kind) => {
    const event = events.find((event) => event.kind === kind);
    if (event) return Promise.resolve(event);
    if (exited) return Promise.reject(new Error(`POC_WORKER_ALREADY_EXITED_${kind}`));
    return new Promise((resolve, reject) => {
      const listener = { kind, resolve, reject };
      listener.timer = setTimeout(() => { pending.splice(pending.indexOf(listener), 1); reject(new Error(`POC_WORKER_TIMEOUT_${kind}`)); }, 15000);
      pending.push(listener);
    });
  };
  return { child, waitFor, resume: (kind) => child.send({ continue: kind }), events };
}
async function start(w) { await w.waitFor('ready'); w.resume('ready'); }
async function initialized(t) {
  const f = await fixture(t);
  await claimBootstrap(f.client, f.schema, f.installationId, f.actors[0], f.token);
  return f;
}
async function terminateBackend(f, pid) {
  const { rows } = await f.client.query('SELECT pg_terminate_backend($1) AS terminated', [pid]);
  assert.equal(rows[0].terminated, true);
  // Wait until the backend is gone rather than depending on an arbitrary sleep.
  for (let i = 0; i < 50; i++) {
    const result = await f.client.query('SELECT 1 FROM pg_stat_activity WHERE pid=$1', [pid]);
    if (!result.rowCount) return;
    await new Promise((resolve) => setTimeout(resolve, 20));
  }
  throw new Error('POC_BACKEND_DID_NOT_TERMINATE');
}

test('PG-01: 20 independent processes compete; exactly one bootstrap commits', { timeout: 30000 }, async (t) => {
  const f = await fixture(t, 20);
  const workers = f.actors.map((actor) => worker(t, f, { action: 'bootstrap', actor, token: f.token }));
  const connected = await Promise.all(workers.map((w) => w.waitFor('connected')));
  assert.equal(new Set(connected.map((c) => c.nodePid)).size, 20);
  assert.equal(new Set(connected.map((c) => c.backendPid)).size, 20);
  await Promise.all(workers.map(start));
  const results = await Promise.all(workers.map((w) => w.waitFor('result')));
  assert.equal(results.filter((r) => r.ok).length, 1);
  assert.ok(results.filter((r) => !r.ok).every((r) => r.code === 'POC_ALREADY_INITIALIZED'));
  assert.equal((await f.client.query("SELECT * FROM principal WHERE role='super_admin'")).rowCount, 1);
  assert.equal((await f.client.query("SELECT * FROM audit WHERE action='bootstrap'")).rowCount, 1);
  const state = (await f.client.query('SELECT * FROM installation')).rows[0];
  assert.ok(state.initialized_at && state.consumed_at);
});

