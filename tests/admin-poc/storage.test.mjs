test('PG-17: bootstrap expiry is rechecked after waiting for the installation lock', async (t) => {
  const f = await fixture(t);
  const w = worker(t, f, { action: 'bootstrap', actor: f.actors[0], token: f.token });
  await w.waitFor('ready');
  const pid = (await w.waitFor('connected')).backendPid;
  await f.client.query("UPDATE installation SET expires_at=clock_timestamp()+interval '800 milliseconds'");
  await f.client.query('BEGIN');
  try {
    await f.client.query('SELECT * FROM installation WHERE singleton FOR UPDATE');
    w.resume('ready');
    let blocked = false;
    for (let i = 0; i < 100; i++) {
      await f.client.query('SELECT pg_stat_clear_snapshot()');
      const row = (await f.client.query('SELECT wait_event_type FROM pg_stat_activity WHERE pid=$1', [pid])).rows[0];
      if (row?.wait_event_type === 'Lock') { blocked = true; break; }
      await new Promise((resolve) => setTimeout(resolve, 10));
    }
    assert.ok(blocked);
    await f.client.query('SELECT pg_sleep(1.0)');
    await f.client.query('COMMIT');
  } finally { await f.client.query('ROLLBACK'); }
  const result = await w.waitFor('result');
  assert.equal(result.ok, false);
  assert.equal(result.code, 'POC_INVALID_BOOTSTRAP');
});
